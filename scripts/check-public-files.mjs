import { execFileSync, spawn } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const forbiddenPath = /(?:^|\/)(?:node_modules|\.next(?:-[^/]*)?|\.audit-build|\.?tmp|backups|coverage|\.vercel|\.temp|\.branches|playwright-report|test-results)(?:\/|$)|\.(?:pem|key|p12|pfx|dump|backup|har)$/i;
const sensitiveEnv = /(?:^|\/)\.env(?:$|\.)/;
const exampleEnv = /(?:^|\/)\.env(?:\.local)?\.example$/;
export function publicFileIssues(name, source, knownSecrets = []) {
  const issues = [];
  if (forbiddenPath.test(name) || (sensitiveEnv.test(name) && !exampleEnv.test(name))) issues.push('arquivo privado ou gerado');
  if (exampleEnv.test(name)) {
    for (const line of source.split(/\r?\n/)) {
      if (!line.trim() || line.trim().startsWith('#')) continue;
      if (!/^[A-Z_][A-Z_0-9]*=(?:|cole_sua_chave_aqui)$/.test(line)) issues.push('template de ambiente preenchido');
    }
  }
  if (/-----BEGIN (?:RSA |EC |OPENSSH |DSA )?PRIVATE KEY-----|\bgh[pousr]_[A-Za-z0-9]{30,}|\bgithub_pat_[A-Za-z0-9_]{30,}|\bsb_secret_[A-Za-z0-9_-]{16,}|\bAKIA[A-Z0-9]{16}\b/.test(source)) issues.push('possível credencial');
  if (/\b(?:postgres(?:ql)?|mysql):\/\/[^\s/:]+:[^\s@]+@/i.test(source)) issues.push('URL de banco com senha');
  for (const match of source.matchAll(/\beyJ[A-Za-z0-9_-]+\.[A-Za-z0-9_-]+\.[A-Za-z0-9_-]+/g)) {
    try {
      const claims = JSON.parse(Buffer.from(match[0].split('.')[1], 'base64url').toString());
      if (claims.role === 'service_role' || claims.sub || (claims.exp && claims.role !== 'anon')) issues.push('token de autenticação');
    } catch { /* A expressão não é um JWT válido. */ }
  }
  if (knownSecrets.some(secret => source.includes(secret))) issues.push('valor secreto do ambiente local');
  return [...new Set(issues)];
}
function git(...args) {
  // Scope the exception to this explicitly selected working copy (Windows sandbox ownership differs).
  // Existing artwork exceeds 50 MB; keep scanning it without truncating Git output.
  return execFileSync('git', ['-c', `safe.directory=${process.cwd().replaceAll('\\', '/')}`, ...args], { encoding: 'utf8', maxBuffer: 128 * 1024 * 1024 });
}
export async function checkPublicFiles(history = false, { worktree = false, artifacts = null } = {}) {
  const knownSecrets = fs.existsSync('.env.local') ? fs.readFileSync('.env.local', 'utf8').split(/\r?\n/).flatMap(line => {
    const match = line.match(/^([A-Z_][A-Z_0-9]*)=(.*)$/);
    if (!match || match[1].startsWith('NEXT_PUBLIC_')) return [];
    const value = match[2].trim().replace(/^(['"])(.*)\1$/, '$2');
    return value.length >= 12 && value !== 'cole_sua_chave_aqui' ? [value] : [];
  }) : [];
  let failures = 0;
  let scanned = 0;
  const report = (name, issues) => {
    if (issues.length) { failures++; console.error(`${name}: ${issues.join(', ')}`); }
  };
  if (artifacts || worktree) {
    let names;
    if (artifacts) {
      const root = path.resolve(artifacts), workspace = path.resolve('.');
      if (!root.startsWith(workspace + path.sep)) throw Error('Os artefatos devem estar dentro deste repositório.');
      const walk = dir => fs.readdirSync(dir, { withFileTypes: true }).flatMap(entry => {
        const name = path.join(dir, entry.name);
        if (entry.isSymbolicLink()) throw Error('Link simbólico em artefatos; revise manualmente.');
        return entry.isDirectory() ? walk(name) : [name];
      });
      names = walk(root);
    } else names = git('ls-files', '--cached', '--others', '--exclude-standard', '-z').split('\0').filter(Boolean);
    for (const name of names) {
      // Artifact paths are generated by definition; scan their contents only.
      const source = fs.readFileSync(name, 'utf8');
      report(name, publicFileIssues(artifacts ? 'artifact-content' : name, source, knownSecrets));
      scanned++;
    }
  } else {
    // Scan each distinct blob once, including binary blobs, across every reachable
    // commit. cat-file streams large artwork instead of spawning Git per file.
    const blobs = new Map(), seenPaths = new Set();
    const refs = history ? git('rev-list', '--all').trim().split(/\r?\n/).filter(Boolean) : [''];
    for (const ref of refs) {
      const entries = (ref ? git('ls-tree', '-r', '-z', ref) : git('ls-files', '--stage', '-z')).split('\0').filter(Boolean);
      for (const entry of entries) {
        const [meta, name] = entry.split('\t');
        const oid = meta.split(' ')[ref ? 2 : 1];
        if (!seenPaths.has(name)) { report(name, publicFileIssues(name, '')); seenPaths.add(name); }
        if (!blobs.has(oid)) blobs.set(oid, name);
      }
    }
    if (!blobs.size) {
      console.log(history ? 'Histórico vazio: nenhum commit importado.' : 'Índice vazio: nenhum conteúdo preparado para verificar.');
      return;
    }
    const child = spawn('git', ['-c', `safe.directory=${process.cwd().replaceAll('\\', '/')}`, 'cat-file', '--batch'], { stdio: ['pipe', 'pipe', 'pipe'] });
    let stderr = ''; child.stderr.on('data', data => { stderr += data; });
    const completion = new Promise((resolve, reject) => { child.on('error', reject); child.on('close', code => code === 0 ? resolve() : reject(Error('Falha na leitura dos objetos Git.'))); });
    child.stdin.end([...blobs.keys()].join('\n') + '\n');
    let header = [], object = null;
    for await (const chunk of child.stdout) {
      let offset = 0;
      while (offset < chunk.length) {
        if (!object) {
          const newline = chunk.indexOf(10, offset);
          if (newline < 0) { header.push(chunk.subarray(offset)); break; }
          header.push(chunk.subarray(offset, newline));
          const [oid, type, size] = Buffer.concat(header).toString().split(' ');
          if (type !== 'blob' || !/^\d+$/.test(size)) throw Error('Objeto Git não suportado; revisão manual necessária.');
          object = { oid, remaining: Number(size), chunks: [] }; header = []; offset = newline + 1;
        }
        const count = Math.min(object.remaining, chunk.length - offset);
        if (count) { object.chunks.push(chunk.subarray(offset, offset + count)); object.remaining -= count; offset += count; }
        if (object.remaining || offset === chunk.length) break;
        if (chunk[offset++] !== 10) throw Error('Delimitador Git inválido.');
        // One copy per blob, rather than copying a multi-megabyte image on every
        // incoming chunk. Secrets may span chunks, so scan the assembled content.
        report(`${history ? object.oid.slice(0, 8) + ' ' : ''}${blobs.get(object.oid)}`, publicFileIssues(blobs.get(object.oid), Buffer.concat(object.chunks).toString('utf8'), knownSecrets));
        scanned++; object = null;
      }
    }
    await completion;
    if (object || header.length || stderr) throw Error('Leitura Git incompleta; revisão manual necessária.');
    if (history) report('mensagens de commits', publicFileIssues('commit-messages', git('log', '--all', '--format=%B'), knownSecrets));
  }
  if (failures) throw new Error(`${failures} arquivo(s) precisam de revisão. Nenhum valor secreto foi exibido.`);
  console.log(`${history ? 'Histórico' : artifacts ? 'Artefatos' : worktree ? 'Árvore de trabalho' : 'Índice Git'}: ${scanned} conteúdos verificados; nenhum segredo detectado pelas regras do scanner.`);
}
if (process.argv[1] && fileURLToPath(import.meta.url) === fs.realpathSync(process.argv[1])) {
  try { await checkPublicFiles(process.argv.includes('--history'), { worktree: process.argv.includes('--worktree'), artifacts: process.argv.includes('--artifacts') ? process.argv[process.argv.indexOf('--artifacts') + 1] : null }); }
  catch (error) { console.error(error.message); process.exitCode = 1; }
}
